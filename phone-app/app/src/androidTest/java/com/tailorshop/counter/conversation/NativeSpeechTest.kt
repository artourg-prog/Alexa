package com.tailorshop.counter.conversation

import androidx.test.platform.app.InstrumentationRegistry
import org.junit.Test
import org.junit.Assert.assertTrue
import org.junit.Assert.assertFalse
import org.json.JSONObject
import org.vosk.Model
import org.vosk.Recognizer

/** Offline synthesized fixtures only: no shop credentials, microphone or production writes. */
class NativeSpeechTest {
    private val instrumentation get()=InstrumentationRegistry.getInstrumentation()
    @Test fun testBothLanguagesAndWakeModels() {
        val context=instrumentation.targetContext
        val speech=OfflineSpeech(context,object:OfflineSpeech.Listener {
            override fun onState(state:String) {}
            override fun onPartial(ru:String,en:String,level:Float) {}
            override fun onSegment(text:String,russian:Boolean,confidence:Double) {}
            override fun onWake(russian:Boolean) {}
            override fun onFailure(message:String) {}
        })
        for(lang in listOf("en","ru")) {
            Model(speech.unpack(lang).path).use { model ->
                Recognizer(model,16000f).use { full ->
                    val bytes=instrumentation.context.assets.open("voice-fixtures/$lang.wav").readBytes()
                    // Locate WAV data; generated by afconvert, so a fixed 44-byte header is not assumed.
                    var pos=12
                    while(String(bytes,pos,4,Charsets.US_ASCII)!="data") {
                        val n=le32(bytes,pos+4);pos+=8+n+(n%2)
                    }
                    val size=le32(bytes,pos+4);pos+=8
                    val heard=StringBuilder();var woke=false;val start=System.nanoTime()
                    var offset=pos
                    while(offset<pos+size) {
                        val count=minOf(3200,pos+size-offset)
                        val chunk=bytes.copyOfRange(offset,offset+count)
                        val done=full.acceptWaveForm(chunk,chunk.size)
                        val w=JSONObject(if(done)full.result else full.partialResult).optString(if(done)"text" else "partial")
                        if(done)heard.append(w).append(' ')
                        woke=woke || OfflineSpeech.wakeWord(w)
                        offset+=count
                    }
                    heard.append(JSONObject(full.finalResult).optString("text"))
                    val millis=(System.nanoTime()-start)/1_000_000
                    android.util.Log.i("SofiaFixture","$lang durationMs=${size/32} decodeMs=$millis wake=$woke heard=$heard")
                    assertTrue("$lang did not detect wake name",woke)
                    assertTrue("$lang missing receipt digits: $heard",SafeIntent.numbers(heard.toString()).contains("12345"))
                    assertTrue("$lang slower than real time",millis<size/32)
                    full.reset()
                    val neg=instrumentation.context.assets.open("voice-fixtures/$lang-negative.wav").readBytes()
                    var ni=12
                    while(String(neg,ni,4,Charsets.US_ASCII)!="data") { val n=le32(neg,ni+4);ni+=8+n+(n%2) }
                    val end=ni+8+le32(neg,ni+4);ni+=8
                    var falseWake=false
                    while(ni<end) {
                        val chunk=neg.copyOfRange(ni,minOf(ni+3200,end));ni+=chunk.size
                        val done=full.acceptWaveForm(chunk,chunk.size)
                        val text=JSONObject(if(done)full.result else full.partialResult).optString(if(done)"text" else "partial")
                        if(OfflineSpeech.wakeWord(text)) { android.util.Log.i("SofiaFixture","falseWake $lang $text");falseWake=true }
                    }
                    assertFalse("$lang triggered without a wake name",falseWake)
                }
            }
        }
        speech.close()
    }
    private fun le32(a:ByteArray,i:Int):Int=(a[i].toInt()and 255) or ((a[i+1].toInt()and 255) shl 8) or ((a[i+2].toInt()and 255) shl 16) or ((a[i+3].toInt()and 255) shl 24)
}
